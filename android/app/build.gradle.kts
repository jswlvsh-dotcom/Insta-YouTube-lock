// Optional release signing. CI (or you) can provide a keystore through these
// environment variables; otherwise release builds are signed with the debug key,
// which is fine for installing the APK on your own phone.
val releaseKeystore: String? = System.getenv("GOWORK_KEYSTORE_FILE")?.takeIf { it.isNotBlank() }

android {
    namespace = "com.jaivish.gowork"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.jaivish.gowork"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = System.getenv("GOWORK_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("GOWORK_KEY_ALIAS")
                keyPassword = System.getenv("GOWORK_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = if (releaseKeystore != null) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

